import os
from glob import glob

def keep_only_n_images(folder, n):
    images = sorted(glob(f"{folder}/images/*.jpg"))[:n]
    labels = [img.replace("images", "labels").replace(".jpg", ".txt") for img in images]

    # Remove excess images and labels
    for f in glob(f"{folder}/images/*.jpg"):
        if f not in images:
            os.remove(f)
    for f in glob(f"{folder}/labels/*.txt"):
        if f not in labels:
            os.remove(f)

