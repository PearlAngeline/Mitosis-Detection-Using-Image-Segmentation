for i, file in enumerate(image_files):
    # Load original and predicted images
    original_img = cv2.imread(os.path.join(orig_dir, file))
    predicted_img = cv2.imread(os.path.join(pred_dir, file))

    # Convert to RGB
    original_img = cv2.cvtColor(original_img, cv2.COLOR_BGR2RGB)
    predicted_img = cv2.cvtColor(predicted_img, cv2.COLOR_BGR2RGB)

    # Plain image
    plt.subplot(num_images, 2, i * 2 + 1)
    plt.imshow(original_img)
    plt.title(f"Plain Image - {file}")
    plt.axis("off")

    # Predicted image with boxes
    plt.subplot(num_images, 2, i * 2 + 2)
    plt.imshow(predicted_img)
    plt.title("Predicted - Bounding Boxes")
    plt.axis("off")

plt.tight_layout()
